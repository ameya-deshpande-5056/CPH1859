#!/usr/bin/env bash
# 00_preloader_entry_guide.sh - Guide for entering MediaTek preloader/BROM mode on CPH1859
# Run this on the HOST while following the steps on the DEVICE.
set -euo pipefail

echo "============================================================"
echo "  CPH1859 (MT6771) MediaTek Preloader / BROM Entry Guide"
echo "============================================================"
echo ""
echo "NEVER SEEN in normal ADB mode: 22d9:2769 (OPPO CPH1859)"
echo "EXPECTED in preloader/BROM:     22d9:0003 (BROM) or 22d9:0006 (preloader)"
echo ""
echo "STEP 1: Power OFF the device completely. Wait 5 seconds."
echo ""
echo "STEP 2: Try ONE of these key combinations while connecting USB:"
echo ""
echo "  Combo A: Hold VOLUME DOWN + POWER, then connect USB cable."
echo "  Combo B: Hold VOLUME UP    + POWER, then connect USB cable."
echo "  Combo C: Hold VOLUME DOWN only, then connect USB cable."
echo "  Combo D: Hold VOLUME UP    only, then connect USB cable."
echo "  Combo E: Hold VOLUME DOWN + VOLUME UP, then connect USB cable."
echo ""
echo "STEP 3: Keep holding keys until the PC makes a USB-connect sound,"
echo "         then release. Device SCREEN MAY STAY BLACK (normal)."
echo ""
echo "STEP 4: On the host, run:  lsusb | grep 22d9"
echo "         Look for a PID OTHER than 2769 (e.g. 0003, 0006, 0007)."
echo ""
echo "STEP 5: Once detected, run:  python3 /home/ameya/mtkclient/mtk.py printgpt"
echo ""
echo "============================================================"
echo "  Host-side monitoring (run in another terminal):"
echo "============================================================"
echo ""
echo "  # Watch for new USB device (PID change from 2769):"
echo "    watch -n 1 'lsusb | grep 22d9'"
echo ""
echo "  # Or run this loop:"
echo "    while true; do lsusb 2>/dev/null | grep 22d9; sleep 1; done"
echo ""
echo "============================================================"
echo "  IMPORTANT NOTES:"
echo "============================================================"
echo "  * If the screen shows anything (logo, fastboot text), you are NOT"
echo "    in preloader mode. Power off and try a different combo."
echo "  * Preloader mode = black screen + new USB PID. That's the target."
echo "  * Prior research: DA upload is BLOCKED by DAA_SIG_VERIFY_FAILED on"
echo "    this build, so partition READS may work but WRITES likely won't."
echo "  * We will BACK UP the boot partition first (read-only), then seek"
echo "    a separate confirmation before ANY write."
echo ""
